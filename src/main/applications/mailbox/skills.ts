export const OPERATE_MAILBOX_SKILL = `
---
name: operate-mailbox
description: 提供邮件的收发和管理功能：查看邮件列表、搜索邮件、阅读邮件内容、发送新邮件、回复邮件、标记已读/未读、收藏/取消收藏、删除邮件。
---

# 邮件操作

本技能提供完整的邮件收发与管理能力。用户可以通过自然语言指令完成所有邮件操作，无需进入邮箱 TUI 界面。

## 前置条件

使用本技能的前提是用户已通过 manage-mailbox 技能配置了至少一个邮箱账号。
如果用户尚未配置邮箱，应引导其先添加邮箱账号。

## 查看邮件

- **getEmailList**：获取当前邮箱的邮件列表（分页），返回每封邮件的 uid、主题、发件人、日期、已读/未读状态等。
- **getEmailContent**：传入 uid 获取邮件完整正文（纯文本），可用于查看详情、生成摘要等。

## 搜索邮件

- **searchEmails**：支持多条件组合搜索——按主题(subject)、发件人(from)、收件人(to)、正文(body)、
  通用关键词(general)、日期范围(dateFrom/dateTo)、已读/未读(unread)、收藏状态(starred)、附件名(attachmentName) 搜索。
- 如果用户只说了一个关键词且没有明确是哪个字段，使用 \`general\` 参数。

## 发送邮件

- **sendEmail**：发送新邮件。需要收件人(to)、主题(subject)、正文(content)，可选抄送(cc)、密送(bcc)、附件路径(attachments)。
- **replyEmail**：回复邮件。需要原邮件 uid 和回复内容，可选 replyAll（回复所有人）。

### 发送邮件的交互规范

发送邮件前应遵循以下规则：
1. 如果用户已明确给出收件人、主题、正文（信息齐全且无歧义），可以直接调用 sendEmail / replyEmail 发送，无需额外确认。
2. 如果缺少必要信息（收件人、主题、正文任一缺失），逐一询问并补齐（每次只问一个问题），补齐后再发送。
3. 如果正文不是用户明确提供，而是由你生成/改写（例如“你帮我写一下再发”），你必须先向用户展示完整拟发送正文，再询问是否发送；仅在用户明确确认后才可调用 sendEmail / replyEmail。
4. 用户要求修改收件人、主题或正文时，不得立即发送；先按要求修改。若正文仍由你生成，需再次确认后再发送。
5. 用户表达“先别发/取消发送/暂不发送”时，立即停止发送流程，不调用发送工具。

## 邮件状态管理

- **markEmailReadStatus**：标记邮件已读/未读。
- **starEmail**：收藏或取消收藏邮件。
- **deleteEmail**：删除指定邮件。

## 注意事项

- 所有工具返回的 uid 是邮件的唯一标识，跨工具通用（getEmailList 返回的 uid 可直接传给 getEmailContent、replyEmail 等）。
- getEmailContent 返回的正文最多 5000 字符，如果 fullLength > 5000 说明正文被截断。
- 搜索结果默认最多 50 条，可通过 limit 和 offset 分页。
`;
