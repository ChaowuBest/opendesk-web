/** Returns a localized translation key for common tool operations. */
export function getToolDisplayNameKey(toolName: unknown): string | undefined {
    const normalized = typeof toolName === 'string' ? toolName.trim() : '';
    if (!normalized) return undefined;
    const shortName = normalized.includes('-') ? normalized.slice(normalized.lastIndexOf('-') + 1) : normalized;
    const explicitKey = TOOL_DISPLAY_KEYS[normalized] || TOOL_DISPLAY_KEYS[shortName];
    if (explicitKey) return explicitKey;
    const builtinName = BUILTIN_TOOL_NAMES.has(normalized)
        ? normalized
        : BUILTIN_TOOL_NAMES.has(shortName)
          ? shortName
          : '';
    return builtinName ? `renderer.taskview.toolName.${builtinName}` : undefined;
}

function splitCamelCase(value: string): string {
    return value.replace(/([a-z0-9])([A-Z])/g, '$1 $2').replace(/([A-Z]+)([A-Z][a-z])/g, '$1 $2');
}

/** Makes an unknown plugin/tool identifier readable without changing its protocol name. */
export function humanizeToolName(toolName: unknown): string {
    const normalized = typeof toolName === 'string' ? toolName.trim() : '';
    if (!normalized) return '';
    return normalized
        .split(/[-_.:\s]+/)
        .filter(Boolean)
        .map((segment) => splitCamelCase(segment))
        .join(' / ')
        .replace(/\s+/g, ' ')
        .trim();
}
